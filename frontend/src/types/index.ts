// ─── Message & Citation Types ──────────────────────────────────────────────

export type MessageRole = 'user' | 'assistant' | 'system';

export interface Citation {
  id: string;
  index: number;           // [1], [2] etc shown inline
  sourceId: string;
  sourceTitle: string;
  excerpt: string;
  page?: number;
  chunkId?: string;
}

export interface EvidenceSection {
  id: string;
  title: string;
  content: string;
  citations: Citation[];
  collapsed: boolean;
}

export interface MessageAttachment {
  id: string;
  name: string;
  type: SupportedFileType;
  size: number;
  url?: string;             // blob URL or remote URL
  status: 'uploading' | 'processing' | 'ready' | 'error';
  error?: string;
}

export interface Message {
  id: string;
  role: MessageRole;
  content: string;
  timestamp: Date;
  attachments?: MessageAttachment[];
  citations?: Citation[];
  evidence?: EvidenceSection[];
  isStreaming?: boolean;
  error?: string;
}

// ─── Session / Conversation ────────────────────────────────────────────────

export interface Session {
  id: string;
  title: string;
  createdAt: Date;
  updatedAt: Date;
  messages: Message[];
  pinnedSources: UploadedFile[];
  messageCount: number;
  preview?: string;         // last message snippet
}

// ─── File Upload ───────────────────────────────────────────────────────────

export type SupportedFileType =
  | 'pdf'
  | 'docx'
  | 'md'
  | 'txt'
  | 'png'
  | 'jpg'
  | 'jpeg'
  | 'webp'
  | 'gif';

/** Maps to backend Document.status column */
export type DocumentStatus =
  | 'uploaded'   // just stored in MinIO, DB row created
  | 'parsing'    // Celery parse_document task running
  | 'parsed'     // Module 2 done — preview available
  | 'indexing'   // Celery embed_document task running
  | 'indexed'    // fully in Qdrant — ready for RAG
  | 'error';

/** Frontend display status (maps multiple backend states to fewer UI states) */
export type FileDisplayStatus = 'uploading' | 'processing' | 'ready' | 'error';

export interface UploadedFile {
  id: string;               // local UUID generated by frontend
  docId?: string;           // server-assigned doc_id from POST /api/v1/upload
  name: string;
  type: SupportedFileType;
  size: number;             // bytes
  uploadedAt: Date;
  status: FileDisplayStatus;
  backendStatus?: DocumentStatus; // raw status from polling
  progress?: number;        // 0-100 (upload phase only)
  error?: string;
  chunkCount?: number;
  url?: string;
  previewUrl?: string;
}

