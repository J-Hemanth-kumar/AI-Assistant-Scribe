// ─── Backend RAG / Edit types ─────────────────────────────────────────────

/**
 * One parsed block from GET /api/v1/chunks/{doc_id}
 * Matches backend ParsedContent model exactly.
 */
export interface ParsedContent {
  doc_id: string;
  chunk_index: number;   // deterministic ordering key
  page_no: number;
  block_index: number;
  text: string;
  font?: string;
  font_size?: number;
  bbox?: [number, number, number, number]; // [x, y, width, height] in PDF pts
}

/**
 * One edit from GET /api/v1/diff/{version_id}
 * chunk_index is the join key — never use string matching.
 */
export interface EditDiff {
  chunk_index: number;
  page_no: number;
  original_text: string;
  updated_text: string;
  reason: string;
}

/** One row in GET /api/v1/versions/{doc_id} */
export interface DocumentVersion {
  version_id: string;
  version_number: number;
  prompt: string;
  created_at: string;
}

// ─── Layout engine types (src/lib/pretext/layout.ts) ─────────────────────

/** Options for the deterministic text layout engine. */
export interface LayoutOptions {
  /**
   * Container pixel width.  Measured once with ResizeObserver — never causes reflow.
   */
  containerWidth: number;
  fontSize: number;   // px
  fontFamily: string; // e.g. "JetBrains Mono" | "Plus Jakarta Sans"
  lineHeight: number; // px — used for height pre-computation
  /** If true, all chars are assumed the same width (faster — correct for monospace). */
  monospace?: boolean;
}

/**
 * One layout line produced by computeLayout().
 * start/end are absolute character offsets into the fullText string.
 */
export interface LayoutLine {
  text: string;
  start: number;  // inclusive char offset in fullText
  end: number;    // exclusive char offset in fullText
  lineIndex: number;
}

// ─── Text map types (src/lib/text/buildTextMap.ts) ────────────────────────

/**
 * Maps a chunk_index to its character-offset range in the fullText string.
 * Built by buildTextMap() — used as the lookup table for edit mapping.
 */
export interface ChunkMapEntry {
  chunk_index: number;
  start: number; // inclusive
  end: number;   // exclusive
}

export interface TextMap {
  fullText: string;
  chunkMap: ChunkMapEntry[];
}

// ─── Diff / highlight types (src/lib/diff/) ───────────────────────────────

/** A character-range highlight produced by mapEditsToRanges(). */
export interface HighlightRange {
  start: number; // absolute char offset in fullText
  end: number;   // absolute char offset in fullText
  type: 'added' | 'removed' | 'modified';
  reason?: string;
  chunk_index: number; // retained for tooltip / side-by-side display
}

/** A text segment produced by applyHighlights() — ready for rendering. */
export interface HighlightSegment {
  text: string;
  type?: 'added' | 'removed' | 'modified'; // undefined = plain text
  reason?: string;
}
